-- 5. If the recipe-nutrition trigger function is installed, make Fiber known only when EVERY ingredient is measured
DO $do$
DECLARE
    v_schema TEXT;
BEGIN
    SELECT n.nspname INTO v_schema
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE p.proname = 'fn_recalc_recipe_nutrition'
    LIMIT 1;

    IF v_schema IS NOT NULL THEN
        EXECUTE format($fn$
CREATE OR REPLACE FUNCTION %1$I.fn_recalc_recipe_nutrition(p_recipe_id INT)
RETURNS void AS $body$
BEGIN
    UPDATE %1$I.""Recipe"" r SET
        ""KcalPerServing"" = ROUND(s.kcal    / r.""Servings"", 2),
        ""ProteinG""       = ROUND(s.protein / r.""Servings"", 2),
        ""CarbG""          = ROUND(s.carb    / r.""Servings"", 2),
        ""FatG""           = ROUND(s.fat     / r.""Servings"", 2),
        ""FiberG""         = CASE WHEN s.has_fiber THEN ROUND(s.fiber / r.""Servings"", 2) ELSE NULL END,
        ""IronMg""         = ROUND(s.iron    / r.""Servings"", 2),
        ""B12Mcg""         = ROUND(s.b12     / r.""Servings"", 2),
        ""CalciumMg""      = ROUND(s.calcium / r.""Servings"", 2),
        ""ZincMg""         = ROUND(s.zinc    / r.""Servings"", 2),
        ""UpdatedAt""      = now()
    FROM (
        SELECT
            COALESCE(SUM(ri.""QuantityG"" * i.""KcalPer100g""    / 100), 0) AS kcal,
            COALESCE(SUM(ri.""QuantityG"" * i.""ProteinPer100g"" / 100), 0) AS protein,
            COALESCE(SUM(ri.""QuantityG"" * i.""CarbPer100g""    / 100), 0) AS carb,
            COALESCE(SUM(ri.""QuantityG"" * i.""FatPer100g""     / 100), 0) AS fat,
            BOOL_AND(i.""FiberPer100g"" IS NOT NULL)                       AS has_fiber,
            COALESCE(SUM(ri.""QuantityG"" * COALESCE(i.""FiberPer100g"", 0) / 100), 0) AS fiber,
            COALESCE(SUM(ri.""QuantityG"" * i.""IronPer100g""    / 100), 0) AS iron,
            COALESCE(SUM(ri.""QuantityG"" * i.""B12Per100g""     / 100), 0) AS b12,
            COALESCE(SUM(ri.""QuantityG"" * i.""CalciumPer100g"" / 100), 0) AS calcium,
            COALESCE(SUM(ri.""QuantityG"" * i.""ZincPer100g""    / 100), 0) AS zinc
        FROM %1$I.""RecipeIngredient"" ri
        JOIN %1$I.""Ingredient"" i ON i.""Id"" = ri.""IngredientId""
        WHERE ri.""RecipeId"" = p_recipe_id
    ) s
    WHERE r.""Id"" = p_recipe_id;
END;
$body$ LANGUAGE plpgsql;
$fn$, v_schema);
    END IF;
END $do$;

