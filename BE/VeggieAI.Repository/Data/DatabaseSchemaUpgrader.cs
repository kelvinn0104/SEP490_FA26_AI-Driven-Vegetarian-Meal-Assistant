using Microsoft.EntityFrameworkCore;

namespace VeggieAI.Repository.Data;

/// <summary>
/// Bổ sung cột/bảng mới cho database PostgreSQL đã tồn tại (EnsureCreated không sửa schema cũ).
/// Mọi lệnh đều idempotent. Nội dung giống database/migrations/20261106_api_audit_fixes.sql.
/// </summary>
public static class DatabaseSchemaUpgrader
{
    private const string Sql = @"
ALTER TABLE veggieai.""User""    ADD COLUMN IF NOT EXISTS ""TokenVersion"" INT NOT NULL DEFAULT 0;
ALTER TABLE veggieai.""User""    ADD COLUMN IF NOT EXISTS ""AvatarUrl""    VARCHAR(500);
ALTER TABLE veggieai.""Recipe""  ADD COLUMN IF NOT EXISTS ""ViewCount""    INT NOT NULL DEFAULT 0;
ALTER TABLE veggieai.""Post""    ADD COLUMN IF NOT EXISTS ""UpdatedAt""    TIMESTAMPTZ;
ALTER TABLE veggieai.""Comment"" ADD COLUMN IF NOT EXISTS ""UpdatedAt""    TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS veggieai.""RefreshToken"" (
    ""Id""              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ""UserId""          INT NOT NULL REFERENCES veggieai.""User""(""Id"") ON DELETE CASCADE,
    ""TokenHash""       VARCHAR(64) NOT NULL,
    ""CreatedAt""       TIMESTAMPTZ NOT NULL DEFAULT now(),
    ""ExpiresAt""       TIMESTAMPTZ NOT NULL,
    ""RevokedAt""       TIMESTAMPTZ,
    ""ReplacedByHash""  VARCHAR(64)
);
CREATE UNIQUE INDEX IF NOT EXISTS ""IX_RefreshToken_TokenHash"" ON veggieai.""RefreshToken"" (""TokenHash"");
CREATE INDEX IF NOT EXISTS ""IX_RefreshToken_UserId"" ON veggieai.""RefreshToken"" (""UserId"");

CREATE TABLE IF NOT EXISTS veggieai.""EmailOtp"" (
    ""Email""              VARCHAR(255) NOT NULL,
    ""Purpose""            VARCHAR(20)  NOT NULL,
    ""CodeHash""           VARCHAR(64),
    ""ExpiresAt""          TIMESTAMPTZ,
    ""FailedAttempts""     INT NOT NULL DEFAULT 0,
    ""ResendAvailableAt""  TIMESTAMPTZ,
    ""SendWindowEndsAt""   TIMESTAMPTZ,
    ""SendCount""          INT NOT NULL DEFAULT 0,
    ""UpdatedAt""          TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (""Email"", ""Purpose"")
);

-- Cho phép quyết định revision (yêu cầu tác giả sửa bài); trước đây vi phạm CHECK nên endpoint revision lỗi 500
ALTER TABLE veggieai.""ModerationLog"" DROP CONSTRAINT IF EXISTS ""ModerationLog_Decision_check"";
ALTER TABLE veggieai.""ModerationLog"" ADD CONSTRAINT ""ModerationLog_Decision_check""
    CHECK (""Decision"" IN ('pending', 'approved', 'rejected', 'revision'));";

    public static void Upgrade(VeggieAIDbContext db)
    {
        if (!db.Database.IsRelational()) return;
        db.Database.ExecuteSqlRaw(Sql);
    }
}
