-- Personal profile + nutrition targets calculated by the system
CREATE TABLE "HealthProfile" (
    "Id"               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId"           INT NOT NULL UNIQUE REFERENCES "User"("Id") ON DELETE CASCADE,
    "Gender"           VARCHAR(10)  NOT NULL CHECK ("Gender" IN ('male', 'female')),
    "DateOfBirth"      DATE         NOT NULL,
    "HeightCm"         NUMERIC(5,1) NOT NULL CHECK ("HeightCm" BETWEEN 50 AND 250),
    "WeightKg"         NUMERIC(5,1) NOT NULL CHECK ("WeightKg" BETWEEN 20 AND 300),
    -- activity factor: sedentary 1.2 | light 1.375 | moderate 1.55 | active 1.725 | very_active 1.9
    "ActivityLevel"    VARCHAR(20)  NOT NULL
                       CHECK ("ActivityLevel" IN ('sedentary', 'light', 'moderate', 'active', 'very_active')),
    "HealthGoal"       VARCHAR(20)  NOT NULL CHECK ("HealthGoal" IN ('loss', 'gain', 'maintain')),
    "Bmi"              NUMERIC(5,2),
    "Bmr"              NUMERIC(7,2),          -- Mifflin-St Jeor
    "Tdee"             NUMERIC(7,2),          -- Bmr x activity factor
    "DailyKcalTarget"  NUMERIC(7,2),
    "ProteinTargetG"   NUMERIC(6,2),
    "CarbTargetG"      NUMERIC(6,2),
    "FatTargetG"       NUMERIC(6,2),
    "IronTargetMg"     NUMERIC(6,2),
    "B12TargetMcg"     NUMERIC(6,2),
    "CalciumTargetMg"  NUMERIC(7,2),
    "ZincTargetMg"     NUMERIC(6,2),
    "UpdatedAt"        TIMESTAMPTZ NOT NULL DEFAULT now()   -- used for 30-day update reminder
);

