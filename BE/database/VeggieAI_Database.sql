CREATE OR REPLACE FUNCTION trg_recipe_servings_changed()
RETURNS trigger AS $$
BEGIN
    PERFORM fn_recalc_recipe_nutrition(NEW."Id");
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER "TR_Recipe_Servings_Recalc"
AFTER UPDATE OF "Servings" ON "Recipe"
FOR EACH ROW EXECUTE FUNCTION trg_recipe_servings_changed();

