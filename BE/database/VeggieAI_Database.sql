-- 10. AUTO-CALCULATE RECIPE NUTRITION PER SERVING
-- =====================================================================

CREATE OR REPLACE FUNCTION fn_recalc_recipe_nutrition(p_recipe_id INT)
RETURNS void AS $$
BEGIN
    UPDATE "Recipe" r SET
        "KcalPerServing" = ROUND(s.kcal    / r."Servings", 2),
        "ProteinG"       = ROUND(s.protein / r."Servings", 2),
        "CarbG"          = ROUND(s.carb    / r."Servings", 2),
        "FatG"           = ROUND(s.fat     / r."Servings", 2),
        "IronMg"         = ROUND(s.iron    / r."Servings", 2),
        "B12Mcg"         = ROUND(s.b12     / r."Servings", 2),
        "CalciumMg"      = ROUND(s.calcium / r."Servings", 2),
        "ZincMg"         = ROUND(s.zinc    / r."Servings", 2),
        "UpdatedAt"      = now()
    FROM (
        SELECT
            COALESCE(SUM(ri."QuantityG" * i."KcalPer100g"    / 100), 0) AS kcal,
            COALESCE(SUM(ri."QuantityG" * i."ProteinPer100g" / 100), 0) AS protein,
            COALESCE(SUM(ri."QuantityG" * i."CarbPer100g"    / 100), 0) AS carb,
            COALESCE(SUM(ri."QuantityG" * i."FatPer100g"     / 100), 0) AS fat,
            COALESCE(SUM(ri."QuantityG" * i."IronPer100g"    / 100), 0) AS iron,
            COALESCE(SUM(ri."QuantityG" * i."B12Per100g"     / 100), 0) AS b12,
            COALESCE(SUM(ri."QuantityG" * i."CalciumPer100g" / 100), 0) AS calcium,
            COALESCE(SUM(ri."QuantityG" * i."ZincPer100g"    / 100), 0) AS zinc
        FROM "RecipeIngredient" ri
        JOIN "Ingredient" i ON i."Id" = ri."IngredientId"
        WHERE ri."RecipeId" = p_recipe_id
    ) s
    WHERE r."Id" = p_recipe_id;
END;
$$ LANGUAGE plpgsql;

-- When ingredients of a recipe change
CREATE OR REPLACE FUNCTION trg_recipe_ingredient_changed()
RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        PERFORM fn_recalc_recipe_nutrition(OLD."RecipeId");
    ELSE
        PERFORM fn_recalc_recipe_nutrition(NEW."RecipeId");
        IF TG_OP = 'UPDATE' AND OLD."RecipeId" <> NEW."RecipeId" THEN
            PERFORM fn_recalc_recipe_nutrition(OLD."RecipeId");
        END IF;
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER "TR_RecipeIngredient_Recalc"
AFTER INSERT OR UPDATE OR DELETE ON "RecipeIngredient"
FOR EACH ROW EXECUTE FUNCTION trg_recipe_ingredient_changed();

-- When a moderator updates nutritional values of an ingredient
CREATE OR REPLACE FUNCTION trg_ingredient_nutrition_changed()
RETURNS trigger AS $$
DECLARE
    v_recipe_id INT;
BEGIN
    FOR v_recipe_id IN
        SELECT "RecipeId" FROM "RecipeIngredient" WHERE "IngredientId" = NEW."Id"
    LOOP
        PERFORM fn_recalc_recipe_nutrition(v_recipe_id);
    END LOOP;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER "TR_Ingredient_Recalc"
AFTER UPDATE OF "KcalPer100g", "ProteinPer100g", "CarbPer100g", "FatPer100g",
                "IronPer100g", "B12Per100g", "CalciumPer100g", "ZincPer100g"
ON "Ingredient"
FOR EACH ROW EXECUTE FUNCTION trg_ingredient_nutrition_changed();

