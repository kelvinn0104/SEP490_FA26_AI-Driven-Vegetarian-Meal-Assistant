--   * User.TokenVersion  : thu hồi JWT khi đăng xuất / đổi / đặt lại mật khẩu / khóa tài khoản
--   * User.AvatarUrl     : ảnh đại diện do người dùng tải lên
--   * Recipe.ViewCount   : lượt xem thật (thay số giả 850 + Id*120)
--   * Post.UpdatedAt, Comment.UpdatedAt : sửa bài / sửa bình luận
--   * RefreshToken       : refresh token có lưu trữ + rotation
--   * EmailOtp           : OTP lưu DB (không mất khi restart/redeploy), dùng cho đăng ký và quên mật khẩu
-- Backend tự chạy đúng các lệnh này khi khởi động (DatabaseSchemaUpgrader). File này để chạy tay bằng pgAdmin nếu cần.
-- Tất cả lệnh đều idempotent (chạy lại nhiều lần không lỗi).
