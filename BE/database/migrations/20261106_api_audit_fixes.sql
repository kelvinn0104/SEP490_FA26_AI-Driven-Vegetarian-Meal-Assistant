SET search_path TO veggieai;

ALTER TABLE "User"    ADD COLUMN IF NOT EXISTS "TokenVersion" INT NOT NULL DEFAULT 0;
ALTER TABLE "User"    ADD COLUMN IF NOT EXISTS "AvatarUrl"    VARCHAR(500);
ALTER TABLE "Recipe"  ADD COLUMN IF NOT EXISTS "ViewCount"    INT NOT NULL DEFAULT 0;
ALTER TABLE "Post"    ADD COLUMN IF NOT EXISTS "UpdatedAt"    TIMESTAMPTZ;
ALTER TABLE "Comment" ADD COLUMN IF NOT EXISTS "UpdatedAt"    TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS "RefreshToken" (
    "Id"              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId"          INT NOT NULL REFERENCES "User"("Id") ON DELETE CASCADE,
    "TokenHash"       VARCHAR(64) NOT NULL,
    "CreatedAt"       TIMESTAMPTZ NOT NULL DEFAULT now(),
    "ExpiresAt"       TIMESTAMPTZ NOT NULL,
    "RevokedAt"       TIMESTAMPTZ,
    "ReplacedByHash"  VARCHAR(64)
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_RefreshToken_TokenHash" ON "RefreshToken" ("TokenHash");
CREATE INDEX IF NOT EXISTS "IX_RefreshToken_UserId" ON "RefreshToken" ("UserId");

CREATE TABLE IF NOT EXISTS "EmailOtp" (
    "Email"              VARCHAR(255) NOT NULL,
    "Purpose"            VARCHAR(20)  NOT NULL,
    "CodeHash"           VARCHAR(64),
    "ExpiresAt"          TIMESTAMPTZ,
    "FailedAttempts"     INT NOT NULL DEFAULT 0,
    "ResendAvailableAt"  TIMESTAMPTZ,
    "SendWindowEndsAt"   TIMESTAMPTZ,
    "SendCount"          INT NOT NULL DEFAULT 0,
    "UpdatedAt"          TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY ("Email", "Purpose")
);

-- Cho phép quyết định 'revision' (yêu cầu tác giả sửa bài) — trước đây vi phạm CHECK nên /api/Moderation/{id}/revision lỗi 500
ALTER TABLE "ModerationLog" DROP CONSTRAINT IF EXISTS "ModerationLog_Decision_check";
ALTER TABLE "ModerationLog" ADD CONSTRAINT "ModerationLog_Decision_check"
    CHECK ("Decision" IN ('pending', 'approved', 'rejected', 'revision'));
