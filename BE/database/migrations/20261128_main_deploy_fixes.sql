SET search_path TO veggieai;

-- 1. Chất xơ (Ingredient / Recipe)
ALTER TABLE veggieai."Ingredient" ADD COLUMN IF NOT EXISTS "FiberPer100g" NUMERIC(6,2);
ALTER TABLE veggieai."Recipe"     ADD COLUMN IF NOT EXISTS "FiberG"       NUMERIC(6,2);

-- 2. Thử thách ăn chay
CREATE TABLE IF NOT EXISTS veggieai."VeganChallenge" (
    "Id"                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Title"             VARCHAR(200) NOT NULL,
    "Slug"              VARCHAR(220) NOT NULL DEFAULT '',
    "Description"       TEXT         NOT NULL DEFAULT '',
    "DurationDays"      INT          NOT NULL DEFAULT 7,
    "Category"          VARCHAR(50)  NOT NULL DEFAULT 'beginner',
    "Difficulty"        VARCHAR(20)  NOT NULL DEFAULT 'easy',
    "BadgeName"         VARCHAR(100) NOT NULL DEFAULT 'Hiệp Sĩ Thực Dưỡng',
    "BadgeIcon"         VARCHAR(50)  NOT NULL DEFAULT 'military_tech',
    "BannerUrl"         VARCHAR(500),
    "ParticipantsCount" INT          NOT NULL DEFAULT 0,
    "CompletedCount"    INT          NOT NULL DEFAULT 0,
    "Status"            VARCHAR(20)  NOT NULL DEFAULT 'active',
    "DailyTasks"        TEXT,
    "NutritionistNote"  TEXT,
    "CreatedBy"         INT REFERENCES veggieai."User"("Id") ON DELETE SET NULL,
    "CreatedAt"         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    "UpdatedAt"         TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS veggieai."ChallengeCheckin" (
    "Id"                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ChallengeId"         INT NOT NULL REFERENCES veggieai."VeganChallenge"("Id") ON DELETE CASCADE,
    "UserId"              INT NOT NULL REFERENCES veggieai."User"("Id") ON DELETE CASCADE,
    "DayNumber"           INT          NOT NULL DEFAULT 1,
    "MealTitle"           VARCHAR(200) NOT NULL DEFAULT '',
    "MediaUrl"            VARCHAR(500),
    "Notes"               TEXT,
    "Status"              VARCHAR(20)  NOT NULL DEFAULT 'pending',
    "NutritionistComment" TEXT,
    "CreatedAt"           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    "ReviewedBy"          INT REFERENCES veggieai."User"("Id") ON DELETE SET NULL,
    "ReviewedAt"          TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS "IX_ChallengeCheckin_ChallengeId" ON veggieai."ChallengeCheckin" ("ChallengeId");
CREATE INDEX IF NOT EXISTS "IX_ChallengeCheckin_UserId"      ON veggieai."ChallengeCheckin" ("UserId");

-- 3. Phần thưởng
CREATE TABLE IF NOT EXISTS veggieai."EcoReward" (
    "Id"              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Title"           VARCHAR(200) NOT NULL,
    "Description"     TEXT         NOT NULL DEFAULT '',
    "PointsRequired"  INT          NOT NULL DEFAULT 500,
    "StockQuantity"   INT          NOT NULL DEFAULT 0,
    "ClaimedQuantity" INT          NOT NULL DEFAULT 0,
    "Category"        VARCHAR(50)  NOT NULL DEFAULT 'voucher',
    "ImageUrl"        VARCHAR(500),
    "Status"          VARCHAR(30)  NOT NULL DEFAULT 'active',
    "CreatedAt"       TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS veggieai."RewardClaim" (
    "Id"          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "RewardId"    INT NOT NULL REFERENCES veggieai."EcoReward"("Id") ON DELETE CASCADE,
    "UserId"      INT NOT NULL REFERENCES veggieai."User"("Id") ON DELETE CASCADE,
    "PointsSpent" INT         NOT NULL DEFAULT 0,
    "Status"      VARCHAR(30) NOT NULL DEFAULT 'pending',
    "ClaimDate"   TIMESTAMPTZ NOT NULL DEFAULT now(),
    "HandledAt"   TIMESTAMPTZ,
    "HandledById" INT REFERENCES veggieai."User"("Id") ON DELETE SET NULL,
    "Notes"       TEXT
);
CREATE INDEX IF NOT EXISTS "IX_RewardClaim_RewardId" ON veggieai."RewardClaim" ("RewardId");
CREATE INDEX IF NOT EXISTS "IX_RewardClaim_UserId"   ON veggieai."RewardClaim" ("UserId");

-- 4. Thông báo broadcast
CREATE TABLE IF NOT EXISTS veggieai."BroadcastNotification" (
    "Id"              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Title"           VARCHAR(200) NOT NULL,
    "Message"         TEXT         NOT NULL,
    "Type"            VARCHAR(50)  NOT NULL DEFAULT 'tip',
    "TargetAudience"  VARCHAR(50)  NOT NULL DEFAULT 'all',
    "Status"          VARCHAR(30)  NOT NULL DEFAULT 'draft',
    "ScheduledAt"     TIMESTAMPTZ,
    "SentAt"          TIMESTAMPTZ,
    "RecipientsCount" INT          NOT NULL DEFAULT 0,
    "OpenRate"        NUMERIC(5,2) NOT NULL DEFAULT 0,
    "ClickCount"      INT          NOT NULL DEFAULT 0,
    "ActionUrl"       VARCHAR(300),
    "CreatedById"     INT REFERENCES veggieai."User"("Id") ON DELETE SET NULL,
    "CreatedAt"       TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- 5. Quét sản phẩm chay
CREATE TABLE IF NOT EXISTS veggieai."VeganProductScan" (
    "Id"                         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ProductName"                VARCHAR(200) NOT NULL,
    "Barcode"                    VARCHAR(50),
    "Brand"                      VARCHAR(100) NOT NULL DEFAULT '',
    "Category"                   VARCHAR(50)  NOT NULL DEFAULT 'beverage',
    "ImageUrl"                   VARCHAR(500),
    "LabelImageUrl"              VARCHAR(500),
    "IngredientListRaw"          TEXT         NOT NULL DEFAULT '',
    "FlaggedNonVeganIngredients" TEXT,
    "VeganStatus"                VARCHAR(30)  NOT NULL DEFAULT 'pending_review',
    "ConfidenceScore"            NUMERIC(5,2) NOT NULL DEFAULT 0,
    "ModeratorVerdict"           VARCHAR(50),
    "NutritionistNotes"          TEXT,
    "SubmittedById"              INT REFERENCES veggieai."User"("Id") ON DELETE SET NULL,
    "ReviewedById"               INT REFERENCES veggieai."User"("Id") ON DELETE SET NULL,
    "ReviewedAt"                 TIMESTAMPTZ,
    "ScanCount"                  INT          NOT NULL DEFAULT 1,
    "CreatedAt"                  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS "IX_VeganProductScan_Barcode" ON veggieai."VeganProductScan" ("Barcode");
