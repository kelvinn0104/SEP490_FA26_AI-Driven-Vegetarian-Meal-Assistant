async (page) => {
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const base = 'http://127.0.0.1:5173';
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.unrouteAll({ behavior: 'wait' });
  await page.goto(base);
  await page.evaluate(() => { localStorage.clear(); sessionStorage.clear(); });
  await page.reload();
  await page.locator('.vp-recipe').first().waitFor({ timeout: 100000 });
  check(await page.locator('.vp-recipe').count() > 0, 'Live recipes missing');
  await page.getByRole('textbox', { name: 'Tìm công thức' }).fill('dau');
  check(await page.locator('.vp-recipe').count() > 0, 'Vietnamese search failed');
  await page.getByRole('textbox', { name: 'Tìm công thức' }).fill('zzzz-no-match');
  await page.getByText('Chưa tìm thấy món phù hợp').waitFor();
  await page.getByRole('button', { name: 'Xóa bộ lọc' }).click();
  await page.locator('.vp-card-image').first().click();
  await page.locator('.vp-detail-top h1').waitFor({ timeout: 100000 });
  check(new URL(page.url()).searchParams.has('id'), 'Detail URL lacks ID');
  const heading = await page.locator('.vp-detail-top h1').innerText();
  await page.reload();
  await page.locator('.vp-detail-top h1').waitFor({ timeout: 100000 });
  check(await page.locator('.vp-detail-top h1').innerText() === heading, 'Detail lost after refresh');
  await page.getByRole('button', { name: 'Lưu món', exact: true }).click();
  await page.getByRole('heading', { name: 'Đăng nhập', exact: true }).waitFor();
  await page.goto(base + '/planner');
  await page.getByText('Lên thực đơn, bớt nghĩ mỗi bữa.').waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  check(!(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)), 'Mobile overflow');
  await page.getByRole('navigation',{name:'Điều hướng nhanh'}).getByRole('link',{name:'Cá nhân',exact:true}).click();
  await page.getByRole('link',{name:'Cộng đồng',exact:true}).click();
  await page.locator('.vp-community-list').waitFor({ timeout:100000 });
  // Test authenticated UI with isolated fixtures. No mutations reach the real backend.
  const user = { id: 999, email: 'fixture@example.test', displayName: 'Người kiểm thử', role: 'AuthorizedUser' };
  const writes = [];
  await page.route('https://veggieai-api.onrender.com/api/**', async route => {
    const req = route.request(); const path = new URL(req.url()).pathname.toLowerCase();
    if (req.method() !== 'GET' && req.method() !== 'OPTIONS') writes.push({ path, body: req.postData(), method: req.method() });
    const ok = data => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ success: true, data }) });
    if (path.endsWith('/auth/me')) return ok(user);
    if (path.endsWith('/chat/sessions') && req.method() === 'POST') return ok({ id: 1 });
    if (path.endsWith('/chat/sessions')) return ok([]);
    if (path.endsWith('/messages') && req.method() === 'POST') return ok({ userMessage: { id: 1, sender: 'user', content: 'Đậu hũ' }, aiMessage: { id: 2, sender: 'ai', content: 'Bạn có thể nấu canh đậu hũ.' } });
    return route.fulfill({ status: 404, contentType: 'application/json', body: JSON.stringify({ message: 'Not found' }) });
  });
  await page.evaluate(u => { localStorage.setItem('token', 'fixture'); localStorage.setItem('veggie_user', JSON.stringify(u)); }, user);
  await page.goto(base + '/chatbot');
  await page.getByRole('textbox', { name: 'Tin nhắn' }).fill('Đậu hũ');
  await page.getByRole('button', { name: 'Gửi tin nhắn' }).click();
  await page.getByText('Bạn có thể nấu canh đậu hũ.').waitFor();
  check(writes.some(w => w.path.endsWith('/messages')), 'Chat did not send request');
  await page.goto(base + '/create-post');
  await page.getByLabel('Tiêu đề', { exact: true }).fill('Bữa chay của tôi');
  await page.getByLabel('Nội dung', { exact: true }).fill('Bữa chay với đậu hũ và nấm tươi.');
  await page.getByRole('button', { name: 'Gửi bài viết' }).click();
  await page.getByRole('alert').filter({ hasText: 'Tính năng này hiện chưa sẵn sàng.' }).waitFor();
  check(await page.getByRole('heading', { name: 'Đã gửi bài viết' }).count() === 0, 'False publish success');
  check(await page.evaluate(() => localStorage.getItem('veggieai_user_created_recipes')) === null, 'Fake local post created');
  await page.goto(base + '/user-profile');
  await page.getByRole('alert').first().waitFor();
  check(await page.getByRole('button', { name: 'Tiếp tục' }).isDisabled(), 'Profile can wipe unknown allergies');
  check(errors.length === 0, 'Browser errors: ' + errors.join('; '));
  await page.unroute('https://veggieai-api.onrender.com/api/**');
  await page.evaluate(() => localStorage.clear());
  await page.goto(base);
}
